// Generates src/styles/tokens.css from tokens/tokens.json (the Pen export).
// Run `pnpm --filter @holypearls/ui tokens`; `tokens:check` fails when the CSS is stale.
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../", import.meta.url);
const source = JSON.parse(readFileSync(new URL("tokens/tokens.json", root), "utf8"));
const spec = source.documentedSpecifications;
const out = new URL("src/styles/tokens.css", root);

const fontFallbacks = {
  "hp-font-display": 'var(--font-geist-sans), "Geist", system-ui, sans-serif',
  "hp-font-ui": 'var(--font-geist-sans), "Geist", system-ui, sans-serif',
  "hp-font-mono": 'var(--font-geist-mono), "Geist Mono", ui-monospace, monospace',
};

const lines = [];
const add = (name, value) => lines.push(`  --${name}: ${value};`);

lines.push("  /* Pen variables resolved for hp-direction: " + source.activeTheme + " */");
for (const [name, value] of Object.entries(source.resolvedActiveValues)) {
  if (!name.startsWith("hp-")) continue; // hf-* is the superseded warm direction.
  const type = source.variables[name].type;
  if (fontFallbacks[name]) add(name, fontFallbacks[name]);
  else if (type === "number") add(name, `${value}px`);
  else add(name, value);
}

lines.push("  /* Spacing scale (Stage 4.1 Signal grid) */");
for (const px of spec.spacing.scalePx) add(`hp-space-${px}`, `${px}px`);

lines.push("  /* Type sizes (Stage 4.2 visual lock) */");
const type = spec.typography;
add("hp-text-display", `${type.displaySizesPx.display}px`);
add("hp-text-h1", `${type.displaySizesPx.h1}px`);
add("hp-text-h2", `${type.displaySizesPx.h2}px`);
const [bodyMin, bodyMax] = type.bodySizePx.split(/[–-]/).map(Number);
add("hp-text-body", `${bodyMin}px`);
add("hp-text-body-lg", `${bodyMax}px`);
add("hp-text-label", `${type.labelSizePx}px`);
add("hp-text-support", `${type.supportSizePx}px`);
add("hp-tracking-display", `${Number.parseFloat(type.displayLetterSpacing) / 100}em`);

lines.push("  /* Geometry, layout and accessibility */");
add("hp-border-width", `${spec.geometry.borderWidthPx}px`);
add("hp-layout-content-width", `${spec.layout.desktopContentWidthPx}px`);
add("hp-layout-margin-desktop", `${spec.layout.desktopMarginPx}px`);
add("hp-layout-gutter-mobile", `${spec.layout.mobileGutterPx[0]}px`);
add("hp-layout-columns", `${spec.layout.desktopGridColumns}`);
add("hp-touch-target", `${spec.contrastAndUse.touchTargetMinPx}px`);
add("hp-focus-ring-width", "2px");

lines.push("  /* Motion */");
const motion = spec.motion;
add("hp-motion-status", `${motion.hoverFocusStatusDurationMs}ms`);
add("hp-motion-dropdown", `${motion.dropdownDurationMs}ms`);
add("hp-motion-card", `${motion.cardFilterAccordionDurationMs}ms`);
add("hp-ease-enter", motion.enterEasing);
add("hp-ease-exit", motion.exitEasing);

const css = `/* Generated by scripts/build-tokens.mjs from tokens/tokens.json. Do not edit. */\n:root {\n${lines.join("\n")}\n}\n`;

if (process.argv.includes("--check")) {
  if (readFileSync(out, "utf8") !== css) {
    console.error("tokens.css is out of date. Run `pnpm --filter @holypearls/ui tokens`.");
    process.exit(1);
  }
  console.log("tokens.css matches tokens.json.");
} else {
  writeFileSync(out, css);
  console.log("Wrote src/styles/tokens.css.");
}
